import numpy as np

week1 = np.array([100, 200, 150, 300, 250, 180, 400])
week2 = np.array([120, 180, 170, 280, 300, 160, 450])

total_sales = week1 + week2


change = week2 - week1


fallen_products = np.where(change < 0)[0] + 1

print("Week 1 Sales:", week1)
print("Week 2 Sales:", week2)
print("Total Sales:", total_sales)
print("Change in Sales:", change)
print("Products with Fallen Sales:", fallen_products)