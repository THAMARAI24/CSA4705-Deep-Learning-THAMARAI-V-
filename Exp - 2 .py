import numpy as np


roll_numbers = np.arange(1, 61)

time_points = np.linspace(0, 1, 50)


zeros = np.zeros(8)


ones = np.ones(8)


print("Roll Numbers:", roll_numbers)
print("Time Points:", time_points)
print("Zeros:", zeros)
print("Ones:", ones)


print("\nLength and dtype:")
print("Roll Numbers:", len(roll_numbers), roll_numbers.dtype)
print("Time Points:", len(time_points), time_points.dtype)
print("Zeros:", len(zeros), zeros.dtype)
print("Ones:", len(ones), ones.dtype)