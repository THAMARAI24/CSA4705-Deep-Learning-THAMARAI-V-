import numpy as np

steps = np.array([
    4500, 5200, 6100, 7000, 8000, 6500, 9000,
    7500, 8200, 6800, 9500, 10000, 7200, 8500,
    9100, 7800, 8800, 10500, 11000, 9200, 8700,
    9800, 11500, 12000, 10200, 9400, 10800, 12500,
    11800, 13000
])


first_week = steps[:7]
last_5_days = steps[-5:]
alternate_days = steps[::2]
reversed_steps = steps[::-1]


print("First Week:", first_week)
print("Last 5 Days:", last_5_days)
print("Every Alternate Day:", alternate_days)
print("Reversed Vector:", reversed_steps)


print("\nLengths:")
print("First Week:", len(first_week))
print("Last 5 Days:", len(last_5_days))
print("Alternate Days:", len(alternate_days))
print("Reversed Vector:", len(reversed_steps))


print("\nCheck:",
      len(first_week) == 7 and
      len(last_5_days) == 5 and
      len(alternate_days) == 15 and
      len(reversed_steps) == 30)