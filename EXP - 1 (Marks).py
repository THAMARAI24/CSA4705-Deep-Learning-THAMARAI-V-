import numpy as np

# Store student marks in a NumPy vector
marks = np.array([85, 92, 78, 96, 88])

# Calculate statistics
print("Marks:", marks)
print("Mean:", np.mean(marks))
print("Minimum:", np.min(marks))
print("Maximum:", np.max(marks))
print("Standard Deviation:", round(np.std(marks), 2))

# Find topper's position using NumPy
topper_index = np.argmax(marks)
print("Topper Position (NumPy):", topper_index + 1)

# Find topper's position using manual scan
max_mark = marks[0]
manual_index = 0

for i in range(1, len(marks)):
    if marks[i] > max_mark:
        max_mark = marks[i]
        manual_index = i

print("Topper Position (Manual):", manual_index + 1)

# Check both methods
print("Check:", topper_index == manual_index)

