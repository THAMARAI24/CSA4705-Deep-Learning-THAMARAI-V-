import numpy as np


usd_prices = np.array([10, 20, 30, 40, 50])


rate = 83.5

inr_prices = usd_prices * rate


discounted_prices = inr_prices * 0.9


print("USD Prices:", usd_prices)
print("INR Prices:", inr_prices)
print("Discounted Prices:", discounted_prices)


expected = 0.9 * 83.5 * usd_prices
print("Check:", np.allclose(discounted_prices, expected))